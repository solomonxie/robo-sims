// Vector stroke font: each glyph is polylines on a grid (cap height 6, x-height 4, baseline 0, descender −2).
export type Pt = [number, number]
export type Polyline = Pt[]

interface Glyph {
  w: number
  lines: Polyline[]
}

const CAP = 6
const SPACING = 1.4
const OVERBAR_Y = 7.3
const OVERBARS = new Set(['̄', '̅'])

/** Points along an ellipse, degrees CCW from +x; `to < from` runs clockwise. */
function arc(cx: number, cy: number, rx: number, ry: number, from: number, to: number): Pt[] {
  const n = Math.max(2, Math.ceil(Math.abs(to - from) / 22.5))
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = ((from + ((to - from) * i) / n) * Math.PI) / 180
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)]
  })
}
const ring = (cx: number, cy: number, rx: number, ry: number) => arc(cx, cy, rx, ry, 0, 360)
const dot = (x: number, y: number): Polyline => [[x, y], [x, y + 0.3]]
