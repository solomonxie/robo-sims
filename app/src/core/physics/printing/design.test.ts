import { medianMs } from '../../stopwatch'
import { bracketMoment, bracketPoint, bracketRing, cleanAngle, edgeView, fitClass, fitView, footBulge, holeView, layerStrength, orientView, overhangView, printSlices, rectRing, scanSpans } from './design'

describe('Design for printing', () => {
  it('scans rings even-odd and splits layers into solid, hanging and bridging segments', () => {
    expect(scanSpans([rectRing(0, 0, 10, 10), rectRing(4, 2, 6, 8)], 5)).toEqual([[0, 4], [6, 10]])
    const L = printSlices([[[0, 0], [2, 0], [2, 1], [8, 1], [8, 0], [10, 0], [10, 2], [0, 2]]], { h: 0.5 })
    expect(L[0].segs.every((s) => s.kind === 'solid')).toBe(true)
    expect(L[2].segs.map((s) => s.kind)).toEqual(['solid', 'bridge', 'solid'])
  })
  it('overhangs: clean to about 60° at 0.2 mm with the fan, thinner layers go steeper; bridges sag with length', () => {
    expect(cleanAngle(0.2, 1)).toBeGreaterThan(55)
    expect(cleanAngle(0.2, 1)).toBeLessThan(65)
    expect(cleanAngle(0.12, 1)).toBeGreaterThan(cleanAngle(0.28, 1))
    expect(cleanAngle(0.2, 0)).toBeLessThan(45)
    expect(overhangView(45, 0.2, 1, 20, 30).droop).toBe(0)
    const steep = overhangView(75, 0.2, 1, 20, 30)
    expect(steep.droop).toBeGreaterThan(0.5)
    expect(overhangView(75, 0.2, 0, 20, 30).droop).toBeGreaterThan(steep.droop)
    expect(overhangView(45, 0.2, 1, 60, 30).sag).toBeGreaterThan(4 * overhangView(45, 0.2, 1, 20, 30).sag)
  })
  it('orientation: layers are weakest across (Hankinson); an L bracket is best on its side, worst standing on its end', () => {
    expect(layerStrength(0)).toBe(1)
    expect(layerStrength(90)).toBeCloseTo(0.5)
    const v = orientView('flat', 30)
    expect(v.best).toBe('side')
    const up = v.all.find((a) => a.o === 'upright')!
    expect(up.supportMm3).toBeGreaterThan(1000)
    expect(v.all.find((a) => a.o === 'corner')!.supportMm3).toBe(0)
    expect(v.scores[1]).toBe(Math.min(...v.scores))
    expect(Math.min(...bracketRing(45).map((p) => p[1]))).toBeCloseTo(0)
    expect(bracketMoment(180, bracketPoint(180, [2, 39]))).toBeLessThan(0.1)
    expect(bracketMoment(45, bracketPoint(45, [2, 2]))).toBe(1)
  })
  it('fits: holes print undersize; elephant foot closes the hole mouth unless chamfered or compensated', () => {
    expect(fitClass(-0.3)).toBe('stuck')
    expect(fitClass(0.2)).toBe('slide')
    const f = fitView(0.2, 0.1, 'none')
    expect(f.gap).toBeCloseTo(0.05)
    expect(f.fit).toBe('snug')
    expect(footBulge()).toBeGreaterThan(0.1)
    expect(f.mouth).toBeLessThan(f.gap)
    expect(fitView(0.2, 0.1, 'chamfer').mouth).toBeCloseTo(f.gap)
    expect(fitView(f.slideCad, 0.1, 'comp').fit).toBe('slide')
  })
  it('holes: a round roof droops more as it grows, teardrop and diamond self-support; vertical holes print small', () => {
    const r = holeView('round', 8, 0.2)
    expect(r.roof).toBeGreaterThan(0.1)
    expect(r.curve[r.curve.length - 1]).toBeGreaterThan(r.curve[0])
    expect(holeView('teardrop', 8, 0.2).roof).toBeLessThan(0.02)
    expect(holeView('diamond', 12, 0.2).roof).toBeLessThan(0.02)
    expect(r.vertical).toBeLessThan(8)
  })
  it('edges: a bed-edge fillet droops, a chamfer hides the foot; inside fillets cut the stress raise', () => {
    const fil = edgeView('fillet', 'fillet', 'fillet', 3, 0.2)
    const ch = edgeView('chamfer', 'chamfer', 'chamfer', 3, 0.2)
    const sq = edgeView('square', 'square', 'square', 3, 0.2)
    expect(fil.droop).toBeGreaterThan(0.15)
    expect(ch.droop).toBe(0)
    expect(ch.foot).toBe(0)
    expect(sq.foot).toBeGreaterThan(0.1)
    expect(fil.kt).toBeLessThan(ch.kt)
    expect(sq.kt).toBe(3)
    expect(ch.cusp).toBeLessThan(fil.cusp)
  })
  it('recomputes well under 100 ms per slider move', () => {
    expect(medianMs(() => overhangView(60, 0.12, 0.5, 60, 30))).toBeLessThan(100)
    expect(medianMs(() => orientView('corner', 40))).toBeLessThan(100)
    expect(medianMs(() => holeView('round', 16, 0.12))).toBeLessThan(100)
    expect(medianMs(() => edgeView('fillet', 'fillet', 'fillet', 4, 0.12))).toBeLessThan(100)
  })
})
