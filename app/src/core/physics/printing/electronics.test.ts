import { medianMs } from '../../stopwatch'
import { BOARD, boardView, cartridgeView, firmwareConfig, firmwareView, fwTopMmS, probeC, probeDegPerCount, probeOhms, probeReading } from './electronics'

describe('Printer electronics', () => {
  it('mainboard: driver heat ∝ I², A4988 shuts down where a TMC2209 runs; 12 V loses torque at speed and doubles heater amps', () => {
    const a = boardView('a4988', 1, 24, 100)
    const t = boardView('tmc2209', 1, 24, 100)
    expect(t.driverW).toBeLessThan(a.driverW)
    expect(boardView('a4988', 2, 24, 100).driverW).toBeCloseTo(4 * boardView('a4988', 1, 24, 100).driverW)
    expect(boardView('a4988', 1.5, 24, 100).state).toBe('off')
    expect(boardView('a4988', 1.5, 24, 100).skips).toBe(true)
    expect(boardView('tmc2209', 1.5, 24, 100).state).not.toBe('off')
    expect(boardView('tmc2209', 0.2, 24, 100).skips).toBe(true)
    expect(t.stepHz).toBeCloseTo(100 * t.spm)
    expect(t.spm).toBe(80)
    expect(boardView('tmc2209', 1, 12, 300).skips).toBe(true)
    expect(boardView('tmc2209', 1, 24, 300).skips).toBe(false)
    expect(boardView('tmc2209', 1, 12, 0).topMmS).toBeLessThan(boardView('tmc2209', 1, 24, 0).topMmS)
    expect(boardView('tmc2209', 1, 12, 0).bedA).toBeCloseTo(2 * t.bedA)
    expect(boardView('tmc2209', 1, 12, 0).bedFetW).toBeCloseTo(4 * t.bedFetW)
    expect(a.vref).toBeCloseTo(Math.SQRT2 * 8 * 0.068, 2)
    expect(t.vref).toBeNull()
    expect(boardView('tmc2209', 1, 24, 0).holdNm).toBeGreaterThan(BOARD.needNm)
  })
  it('firmware: Klipper offloads planning to the host, so the same 8-bit MCU goes faster; microsteps cost step rate', () => {
    expect(fwTopMmS('klipper8', 16)).toBeGreaterThan(3 * fwTopMmS('marlin8', 16))
    expect(fwTopMmS('marlin32', 16)).toBeGreaterThan(fwTopMmS('klipper8', 16))
    expect(fwTopMmS('marlin8', 64)).toBeLessThan(fwTopMmS('marlin8', 16) / 2)
    const m = firmwareView('marlin8', 300, 16)
    expect(m.keeps).toBe(false)
    expect(m.actualMmS).toBeCloseTo(m.top)
    const k = firmwareView('klipper8', 300, 16)
    expect(k.keeps).toBe(true)
    expect(k.tasks[0]).toBe(0)
    expect(k.tasks[1]).toBe(0)
    expect(k.hostPct).toBeGreaterThan(0)
    expect(k.hostPct).toBeLessThan(0.2)
    expect(m.load).toBeCloseTo(m.tasks.reduce((s, x) => s + x, 0))
    expect(firmwareView('marlin8', 100, 16).load).toBeCloseTo(m.load / 3)
    expect(firmwareConfig('marlin8', 16).join(' ')).toContain('{ 80, 80, 400, 93 }')
    expect(firmwareConfig('klipper8', 32).join(' ')).toContain('microsteps: 32')
  })
  it('thermistor: Beta / CVD round trip, NTC resolution coarsens hot while PT1000 stays even; faults trip MIN/MAXTEMP', () => {
    for (const p of ['ntc', 'pt1000'] as const) for (const c of [25, 150, 280]) expect(probeC(p, probeOhms(p, c))).toBeCloseTo(c, 6)
    expect(probeOhms('ntc', 25)).toBeCloseTo(100e3)
    expect(probeOhms('pt1000', 0)).toBeCloseTo(1000)
    expect(probeDegPerCount('ntc', 350)).toBeGreaterThan(5 * probeDegPerCount('ntc', 150))
    expect(probeDegPerCount('pt1000', 350)).toBeLessThan(probeDegPerCount('ntc', 350))
    expect(probeDegPerCount('pt1000', 350) / probeDegPerCount('pt1000', 50)).toBeLessThan(2)
    const r = probeReading('ntc', 210, 'none')
    expect(Math.abs(r.readC - 210)).toBeLessThan(r.perCount)
    expect(r.error).toBeNull()
    expect(probeReading('ntc', 210, 'open').error).toBe('MINTEMP')
    expect(probeReading('ntc', 210, 'short').error).toBe('MAXTEMP')
    expect(probeReading('pt1000', 210, 'open').error).toBe('MAXTEMP')
    expect(probeReading('pt1000', 210, 'short').error).toBe('MINTEMP')
    expect(probeReading('ntc', 210, 'loose').readC).toBeLessThan(120)
    expect(probeReading('ntc', 320, 'none').error).toBe('MAXTEMP')
    expect(probeReading('pt1000', 320, 'none').error).toBeNull()
  })
  it('cartridge: P = V²/R, wrong supply gives ¼ or 4× power; PWM duty holds the setpoint', () => {
    const ok = cartridgeView('r24w40', 220)
    expect(ok.ohms).toBeCloseTo(14.4)
    expect(ok.watts).toBeCloseTo(40)
    expect(cartridgeView('r24on12', 220).watts).toBeCloseTo(10)
    expect(cartridgeView('r24on12', 220).reaches).toBe(false)
    expect(cartridgeView('r12on24', 220).watts).toBeCloseTo(160)
    expect(cartridgeView('r12on24', 220).over).toBe(true)
    expect(cartridgeView('r24w60', 220).heatS).toBeLessThan(ok.heatS)
    expect(ok.heatS).toBeGreaterThan(30)
    expect(ok.heatS).toBeLessThan(120)
    expect(ok.duty * ok.watts).toBeCloseTo(ok.holdW)
    expect(cartridgeView('r12w40', 220).amps).toBeCloseTo(2 * ok.amps)
  })
  it('slider recompute is fast', () => {
    const ms = medianMs((i) => {
      boardView('tmc2209', 0.5 + (i % 5) * 0.2, 24, 150)
      firmwareView('marlin8', 100 + i, 32)
      for (let c = 0; c <= 400; c += 5) probeReading('ntc', c, 'none')
      cartridgeView('r24w40', 200 + i)
    })
    expect(ms).toBeLessThan(100)
  })
})
