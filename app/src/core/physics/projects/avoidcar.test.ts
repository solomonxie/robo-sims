import { medianMs } from '../../stopwatch'
import { LOOK_STATES, echoPinSafe, echoPinVolts, floorEcho, lookRun, mountScan, servoWaitS, stopPing, stopRun, stopSheet } from './avoidcar'

describe('Obstacle-avoiding car', () => {
  it('mount: too low or tilted down hears the floor; too high misses low things; the ECHO pin needs a divider', () => {
    expect(floorEcho(0.03, 0).m).not.toBeNull()
    expect(floorEcho(0.08, 0).m).toBeNull()
    expect(floorEcho(0.08, 10).m).not.toBeNull()
    expect(floorEcho(0.08, -10).peak).toBeLessThan(floorEcho(0.08, 0).peak)
    const low = mountScan(0.03, 0, 'wall')
    expect(low.seenFromM).toBeLessThan(0.15)
    expect(low.frames[0].src).toBe('floor')
    const good = mountScan(0.08, 0, 'wall')
    expect(good.seenFromM).toBeCloseTo(1.5)
    expect(good.frames[0].cm).toBeCloseTo(150, -1)
    const sill = mountScan(0.08, 0, 'sill')
    expect(sill.seenFromM).toBeLessThan(0.6)
    expect(sill.lostAtM).toBeGreaterThan(0.1)
    expect(mountScan(0.12, 0, 'sill').seenFromM).toBeNull()
    expect(mountScan(0.12, 0, 'box').seenFromM).toBeLessThan(good.seenFromM!)
    expect(echoPinVolts(true)).toBeCloseTo(3.33, 2)
    expect(echoPinSafe(false)).toBe(false)
    expect(echoPinSafe(true)).toBe(true)
  })
  it('logic: looking both ways bumps less than always spinning left, but spends time looking', () => {
    const left = lookRun('left', 0.2)
    const look = lookRun('look', 0.2)
    expect(look.bumps).toBeLessThan(left.bumps / 2)
    expect(look.dist).toBeLessThan(left.dist)
    expect(new Set(look.look.map((f) => f.state)).size).toBeGreaterThanOrEqual(5)
    expect(left.look.some((f) => f.state === 'LOOK LEFT')).toBe(false)
    expect(look.frames.every((f) => LOOK_STATES[f.rule] !== undefined)).toBe(true)
    expect(servoWaitS(0, 70)).toBeGreaterThan(0.1)
    expect(servoWaitS(70, -70)).toBeGreaterThan(servoWaitS(0, 70))
  })
  it('test: square walls, foam and legs stop; a 45° wall is never heard; slow pings at speed crash', () => {
    expect(stopPing('wall', 0)).toBeCloseTo(120, -1)
    expect(stopPing('steep', 0.5)).toBe(0)
    expect(stopPing('foam', 0)).toBe(0)
    expect(stopPing('foam', 0.6)).toBeGreaterThan(0)
    const sheet = stopSheet(0.6, 0.2, 0.06)
    expect(sheet.filter((s) => s.crashed).map((s) => s.target)).toEqual(['steep'])
    expect(stopRun('leg', 0.6, 0.2, 0.06).seenM).toBeLessThan(0.8)
    const slow = stopRun('wall', 0.8, 0.15, 0.25)
    expect(slow.crashed).toBe(true)
    expect(stopRun('wall', 0.8, 0.15, 0.06).crashed).toBe(false)
    expect(stopRun('wall', 0.6, 0.25, 0.06).gapM).toBeGreaterThan(stopRun('wall', 0.6, 0.15, 0.06).gapM)
  })
  it('speed: scans and runs stay quick', () => {
    expect(medianMs(() => {
      mountScan(0.05, 5, 'sill')
      stopSheet(0.7, 0.2, 0.25)
    })).toBeLessThan(200)
    expect(medianMs(() => lookRun('look', 0.25), 3)).toBeLessThan(1500)
  })
})
