import { medianMs } from '../../stopwatch'
import { DRIVE, PHONE_CAR, carPower, drvMode, phoneCarRun, pwmWheelSpeed, spinMs, pwmSquareRun, startDuty, wiredDrive } from './robocar'

describe('Robo-car', () => {
  it('power: 2S 18650 runs everything; AA resets on a hard start; one cell cannot feed the buck', () => {
    const li2 = carPower('li2')
    expect(li2.verdict).toBe('ok')
    expect(li2.cruise.railV).toBeCloseTo(5, 1)
    expect(li2.stall.mcuV).toBeCloseTo(3.3, 1)
    expect(li2.cruise.speed).toBeGreaterThan(carPower('aa4').cruise.speed)
    expect(li2.hours).toBeGreaterThan(2)
    expect(li2.stall.motorA).toBeGreaterThan(li2.cruise.amps * 4)
    const aa = carPower('aa4')
    expect(aa.verdict).toBe('resets')
    expect(aa.stall.packV).toBeLessThan(aa.cruise.packV - 0.5)
    expect(carPower('li1').verdict).toBe('noLogic')
    expect(carPower('nimh4').cruise.railV).toBeLessThan(5)
    expect(carPower('nimh4').verdict).toBe('dips')
  })
  it('driver: DRV8833 truth table and the classic wiring faults', () => {
    expect([drvMode(true, false), drvMode(false, true), drvMode(true, true), drvMode(false, false)]).toEqual(['forward', 'reverse', 'brake', 'coast'])
    const ok = wiredDrive('forward', 'ok')
    expect(ok.ok).toBe(true)
    expect(ok.v).toBeGreaterThan(0)
    expect(ok.w).toBeCloseTo(0)
    const sw = wiredDrive('forward', 'swapped')
    expect(sw.v).toBeCloseTo(0)
    expect(sw.w).toBeLessThan(0)
    expect(wiredDrive('forward', 'noGround').dirs).toEqual([0, 0])
    expect(wiredDrive('forward', 'inputOnly').dirs).toEqual([1, 0])
    expect(wiredDrive('reverse', 'inputOnly').ok).toBe(true)
    expect(wiredDrive('spin', 'ok').w).toBeLessThan(0)
  })
  it('PWM: no motion below the start duty; the weak right motor curves the square until trimmed', () => {
    const d0 = startDuty()
    expect(d0).toBeGreaterThan(0.05)
    expect(d0).toBeLessThan(0.3)
    expect(pwmWheelSpeed(d0 - 0.01)).toBe(0)
    expect(pwmWheelSpeed(0.7)).toBeLessThan(pwmWheelSpeed(1))
    expect(spinMs() % 10).toBe(0)
    const raw = pwmSquareRun(DRIVE.tunedDuty, 0)
    expect(raw.driftM).toBeLessThan(-0.1)
    expect(raw.turnDeg).toBeLessThan(80)
    const trimmed = pwmSquareRun(DRIVE.tunedDuty, 0.06)
    expect(Math.abs(trimmed.driftM)).toBeLessThan(0.04)
    expect(Math.abs(trimmed.turnDeg - 90)).toBeLessThan(5)
    expect(trimmed.missM).toBeLessThan(raw.missM / 5)
    expect(Math.abs(pwmSquareRun(0.5, 0.06).turnDeg - 90)).toBeGreaterThan(15)
  })
  it('phone: a locked phone leaves the last command running unless the robot times out', () => {
    const none = phoneCarRun(0, 0.5)
    expect(none.crashed).toBe(true)
    const fast = phoneCarRun(0.3, 0.5)
    expect(fast.crashed).toBe(false)
    expect(fast.blindM).toBeLessThan(0.1)
    expect(fast.stoppedAt).toBeLessThan(PHONE_CAR.lockAt + 0.5)
    expect(phoneCarRun(1, 0.5).blindM).toBeGreaterThan(fast.blindM * 2)
    expect(phoneCarRun(1, 0.8).crashed).toBe(true)
    const f = none.frames[Math.round(1 / PHONE_CAR.dt)]
    expect(f.wl).toBeCloseTo(f.wr)
    expect(none.frames[Math.round(0.3 / PHONE_CAR.dt)].wl).toBe(0)
  })
  it('speed: power tree, square and phone runs stay quick', () => {
    expect(medianMs(() => {
      carPower('aa4')
      pwmSquareRun(0.6, 0.03)
      phoneCarRun(1, 0.7)
    })).toBeLessThan(200)
  })
})
