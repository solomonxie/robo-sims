import { amps, rpmText, timeText, bytesText, dbmText, factorText, mat2Text, tupleText, fitDigits, hoursText, durationText, dayClock, degWhole, joules, spanText, mA, mAText, millivolts, msText, niceCeil, ohms, sci, si, signed, superscript, volts, watts } from './units'

describe('units', () => {
  it('always signs fixed-point text', () => {
    expect(signed(1)).toBe('+1.0')
    expect(signed(-0.456, 2)).toBe('−0.46')
    expect(signed(0, 0)).toBe('+0')
  })

  it('formats with SI prefixes and scientific notation', () => {
    expect(si(0.0123, 'A')).toBe('12.3 mA')
    expect(si(4700, 'Ω', 2)).toBe('4.7 kΩ')
    expect(si(0, 'V')).toBe('0 V')
    expect(si(3e-9, 'm')).toBe('3 nm')
    expect(si(2e-15, 'J')).toBe('2 fJ')
    expect(sci(6.24e18)).toBe('6.24 × 10¹⁸')
    expect(sci(2.5e-5)).toBe('2.5 × 10⁻⁵')
    expect(superscript(-12)).toBe('⁻¹²')
  })
  it('formats volts, amps, ohms, watts, joules to 3 digits', () => {
    expect(volts(4.5)).toBe('4.5 V')
    expect(amps(0.0123)).toBe('12.3 mA')
    expect(ohms(4700)).toBe('4.7 kΩ')
    expect(watts(1.2345)).toBe('1.23 W')
    expect(joules(3600)).toBe('3.6 kJ')
    expect(mA(0.02)).toBe(20)
    expect(millivolts(0.0424)).toBe('42 mV')
    expect(hoursText(0.5)).toBe('30 min')
    expect(hoursText(2.345)).toBe('2.3 h')
    expect(hoursText(2.345, 2)).toBe('2.35 h')
    expect(timeText(2.5e-6)).toBe('2.5 µs')
    expect(timeText(Infinity)).toBe('never')
    expect(rpmText(109.6)).toBe('110 rpm')
    expect(durationText(1800)).toBe('30 min')
    expect(durationText(9000)).toBe('2.5 h')
    expect(dayClock(31.5)).toBe('day 2, 07:30')
    expect(degWhole(-12.6)).toBe('-13°')
    expect(spanText(30)).toBe('30 h')
    expect(spanText(240)).toBe('10 days')
    expect(spanText(8766 * 2.34)).toBe('2.3 years')
  })
  it('fits a number into seven-segment cells with the most decimals', () => {
    expect(fitDigits(6, 3)).toBe('6.00')
    expect(fitDigits(27.27, 3)).toBe('27.3')
    expect(fitDigits(220, 3)).toBe('220')
    expect(fitDigits(1000, 4)).toBe('1000')
    expect(fitDigits(9.996, 3)).toBe('10.0')
    expect(fitDigits(-3, 4)).toBe('-3.00')
    expect(fitDigits(0, 2)).toBe('0.0')
  })

  it('rounds up to a 1-2-5 step', () => {
    expect(niceCeil(0.03)).toBeCloseTo(0.05, 12)
    expect(niceCeil(7)).toBe(10)
    expect(niceCeil(2)).toBe(2)
    expect(niceCeil(0.0011)).toBeCloseTo(0.002, 12)
    expect(niceCeil(0)).toBe(0)
  })
  it('formats binary sizes', () => {
    expect(bytesText(512)).toBe('512 B')
    expect(bytesText(0x5000)).toBe('20 KB')
    expect(bytesText(0x140000)).toBe('1.25 MB')
    expect(bytesText(0x160000)).toBe('1.375 MB')
  })
  it('formats ms, mA and dBm', () => {
    expect(msText(0.25)).toBe('250 ms')
    expect(msText(0.0042)).toBe('4.2 ms')
    expect(msText(0.00425, 2)).toBe('4.25 ms')
    expect(mAText(0.02)).toBe('20 mA')
    expect(mAText(0.005)).toBe('5.0 mA')
    expect(dbmText(-67.4)).toBe('−67 dBm')
    expect(dbmText(-0.2)).toBe('0 dBm')
  })
  test('tuples, factors and 2×2 matrices', () => {
    expect(tupleText([1, -0.5, 0.001])).toBe('(1.00, −0.50, 0.00)')
    expect(factorText(-0.5)).toBe('(−0.50)')
    expect(factorText(0.5)).toBe('0.50')
    expect(mat2Text([1, 0, -1, 2])).toBe('[1.00 0.00; −1.00 2.00]')
  })
})
