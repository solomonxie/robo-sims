// node tools/bake-speech-nets.mjs — retrains the speech nets and rewrites src/core/physics/ai/speechNets.ts.
import { build } from 'esbuild'
import { writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const app = join(dirname(fileURLToPath(import.meta.url)), '..')
const { outputFiles } = await build({
  stdin: { contents: "export { trainKwsNet, trainCmdNet } from './src/core/physics/ai/speech'", resolveDir: app, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  logLevel: 'error',
})
const { trainKwsNet, trainCmdNet } = await import(`data:text/javascript,${encodeURIComponent(outputFiles[0].text)}`)
const layers = (net) => net.map((L) => `    ${JSON.stringify(L)},`).join('\n')
const nets = Object.entries({ kws: trainKwsNet(), cmd: trainCmdNet() }).map(([k, net]) => `  ${k}: [\n${layers(net)}\n  ],`).join('\n')
writeFileSync(
  join(app, 'src/core/physics/ai/speechNets.ts'),
  `// Generated by tools/bake-speech-nets.mjs: the trained speech nets, so the lesson opens without training.\nimport { Mlp } from './net'\n\nexport const SPEECH_NETS: { kws: Mlp; cmd: Mlp } = {\n${nets}\n}\n`,
)
